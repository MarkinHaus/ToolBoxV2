"""R1 (V3): Genau eine .env - ein Pfad, ein Leser, ein Schreiber.

Regelwerk 2026-11-11 Version 3, R1:
- Pfadregel liegt in _state_dir.env_file() (packaged -> user_state_dir()/.env,
  source -> Repo-Root .env). TB_DATA_DIR ist KEIN .env-Kandidat mehr.
- save_env_file ist der einzige Schreiber, load_existing_env der einzige Leser.
"""
import os
import tempfile
import unittest
from pathlib import Path
from unittest import mock


class EnvFileRuleTest(unittest.TestCase):
    KEYS = ("TB_INSTALL_DIR", "TB_DATA_DIR")

    def setUp(self):
        self._saved = {k: os.environ.get(k) for k in self.KEYS}
        for k in self.KEYS:
            os.environ.pop(k, None)
        self._tmp = tempfile.TemporaryDirectory()
        self.tmp = Path(self._tmp.name)

    def tearDown(self):
        for k, v in self._saved.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v
        self._tmp.cleanup()

    def _packaged(self, install_dir):
        import toolboxv2._state_dir as sd
        os.environ["TB_INSTALL_DIR"] = str(install_dir)
        return mock.patch.object(sd, "is_packaged_install", lambda: True)

    def test_packaged_uses_install_dir_not_data_dir(self):
        from toolboxv2 import _state_dir
        with self._packaged(self.tmp / "install"):
            os.environ["TB_DATA_DIR"] = str(self.tmp / "elsewhere")
            p = _state_dir.env_file()
        self.assertEqual(Path(self.tmp) / "install" / ".env", Path(p))
        self.assertNotIn("elsewhere", str(p))

    def test_source_checkout_uses_repo_root(self):
        from toolboxv2 import _state_dir
        with mock.patch.object(_state_dir, "is_packaged_install", lambda: False):
            p = _state_dir.env_file()
        self.assertEqual(
            Path(_state_dir.__file__).resolve().parent.parent / ".env",
            Path(p).resolve())

    def test_writable_env_path_delegates_to_env_file(self):
        from toolboxv2 import _state_dir
        import toolboxv2.init_onboarding as io_mod
        with self._packaged(self.tmp / "install"):
            self.assertEqual(_state_dir.env_file(), Path(io_mod._writable_env_path()))

    def test_no_second_writer_or_reader_in_onboarding(self):
        import toolboxv2.init_onboarding as io_mod
        self.assertFalse(hasattr(io_mod, "_append_env"), "R1: _append_env must be gone")
        self.assertFalse(hasattr(io_mod, "_read_env_file"), "R1: _read_env_file must be gone")

    def test_tb_data_dir_alone_never_creates_env(self):
        from toolboxv2 import _state_dir
        os.environ["TB_DATA_DIR"] = str(self.tmp / "data")
        with mock.patch.object(_state_dir, "is_packaged_install", lambda: False):
            p = _state_dir.env_file()
        self.assertNotEqual(Path(self.tmp) / "data" / ".env", Path(p))


class SaveLoadRoundtripTest(unittest.TestCase):
    """cp1252-Fremdbytes ueberleben save_env_file/load_existing_env (RT1)."""

    def test_cp1252_bytes_survive_save(self):
        from toolboxv2.utils.clis.config_wizard import save_env_file, load_existing_env
        with tempfile.TemporaryDirectory() as td:
            env = Path(td) / ".env"
            env.write_bytes(
                ("# ToolBoxV2 Environment \u2013 generated by installer\n"
                 "TOOLBOX_HOME=C:\\tb\nTB_JWT_SECRET=\n").encode("cp1252"))
            save_env_file(env, {"TB_JWT_SECRET": "abc123"})
            raw = env.read_bytes()
            self.assertIn(b"TB_JWT_SECRET=abc123", raw)
            self.assertIn(b"generated by installer", raw)
            loaded = load_existing_env(env)
            self.assertEqual("abc123", loaded["TB_JWT_SECRET"])
            self.assertEqual("C:\\tb", loaded["TOOLBOX_HOME"])


if __name__ == "__main__":
    unittest.main()
