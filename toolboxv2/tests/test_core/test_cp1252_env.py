"""RT1: ensure_secret must survive a cp1252-encoded installer .env (en-dash header).

R1 (V3): the installer .env lives in the installation folder
(TB_INSTALL_DIR/.env for packaged installs), not in TB_DATA_DIR.
"""
import os
import tempfile
import unittest
from pathlib import Path
from unittest import mock


class Cp1252EnvTest(unittest.TestCase):
    KEYS = ("TB_JWT_SECRET", "TB_COOKIE_SECRET", "TB_DATA_DIR", "TB_INSTALL_DIR")

    def setUp(self):
        self._saved = {k: os.environ.get(k) for k in self.KEYS}
        for k in self.KEYS:
            os.environ.pop(k, None)
        self._tmp = tempfile.TemporaryDirectory()
        self.install = Path(self._tmp.name) / "install"
        self.install.mkdir(parents=True)
        # installer.ps1 output: en-dash header in cp1252, empty secret lines
        content = (
            "# ToolBoxV2 Environment \u2013 generated by installer\n"
            "TOOLBOX_HOME=C:\\tb\n"
            "TB_JWT_SECRET=\n"
            "TB_COOKIE_SECRET=\n"
        )
        (self.install / ".env").write_bytes(content.encode("cp1252"))

    def tearDown(self):
        for k, v in self._saved.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v
        self._tmp.cleanup()

    def test_ensure_secret_survives_cp1252_env(self):
        import toolboxv2._state_dir as sd
        from toolboxv2.init_onboarding import ensure_secret
        os.environ["TB_INSTALL_DIR"] = str(self.install)
        with mock.patch.object(sd, "is_packaged_install", lambda: True):
            s1 = ensure_secret(persist=True)   # must not raise UnicodeDecodeError
        self.assertTrue(s1 and len(s1) >= 64)
        raw = (self.install / ".env").read_bytes()
        self.assertIn(f"TB_JWT_SECRET={s1}".encode(), raw)
        # foreign bytes (en-dash header) must survive round-trip
        self.assertIn(b"generated by installer", raw)


if __name__ == "__main__":
    unittest.main()
