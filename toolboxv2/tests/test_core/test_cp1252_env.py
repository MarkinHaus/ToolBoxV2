"""RT1: ensure_secret must survive a cp1252-encoded installer .env (en-dash header)."""
import os
import tempfile
import unittest
from pathlib import Path


class Cp1252EnvTest(unittest.TestCase):
    KEYS = ("TB_JWT_SECRET", "TB_COOKIE_SECRET", "TB_DATA_DIR")

    def setUp(self):
        self._saved = {k: os.environ.get(k) for k in self.KEYS}
        for k in self.KEYS:
            os.environ.pop(k, None)
        self._tmp = tempfile.TemporaryDirectory()
        self.data = Path(self._tmp.name) / "data"
        self.data.mkdir(parents=True)
        os.environ["TB_DATA_DIR"] = str(self.data)
        # installer.ps1 output: en-dash header in cp1252, empty secret lines
        content = (
            "# ToolBoxV2 Environment \u2013 generated by installer\n"
            "TOOLBOX_HOME=C:\\tb\n"
            "TB_JWT_SECRET=\n"
            "TB_COOKIE_SECRET=\n"
        )
        (self.data / ".env").write_bytes(content.encode("cp1252"))

    def tearDown(self):
        for k, v in self._saved.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v
        self._tmp.cleanup()

    def test_ensure_secret_survives_cp1252_env(self):
        from toolboxv2.init_onboarding import ensure_secret
        s1 = ensure_secret(persist=True)   # must not raise UnicodeDecodeError
        self.assertTrue(s1 and len(s1) >= 64)
        raw = (self.data / ".env").read_bytes()
        self.assertIn(f'TB_JWT_SECRET="{s1}"'.encode(), raw)
        # foreign bytes (en-dash header) must survive round-trip
        self.assertIn(b"generated by installer", raw)


if __name__ == "__main__":
    unittest.main()
